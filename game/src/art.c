static uint8_t tile_buf[16];

/* Converts one 64-char tile to 2bpp in tile_buf. */
static void conv_tile(const char *src) {
  uint8_t r, c, lo, hi, v;
  for (r = 0; r < 8; r++) {
    lo = 0; hi = 0;
    for (c = 0; c < 8; c++) {
      v = (uint8_t)(src[(r << 3) + c] - '0');
      lo = (uint8_t)((lo << 1) | (v & 1));
      hi = (uint8_t)((hi << 1) | ((v >> 1) & 1));
    }
    tile_buf[r << 1] = lo;
    tile_buf[(r << 1) + 1] = hi;
  }
}

/* Converts one 35-char glyph (5x7) to a 2bpp tile in tile_buf, set in columns 1..5, rows 0..6. */
static void conv_glyph(const char *src) {
  uint8_t r, c, bits;
  for (r = 0; r < 8; r++) {
    bits = 0;
    if (r < 7) {
      for (c = 0; c < 5; c++) {
        bits = (uint8_t)(bits << 1);
        if (src[r * 5 + c] == '#') bits |= 1;
      }
      bits = (uint8_t)(bits << 2);
    }
    tile_buf[r << 1] = bits;
    tile_buf[(r << 1) + 1] = bits;
  }
}

void load_art(void) {
  uint8_t i;
  for (i = 0; i < BG_TILE_COUNT; i++) {
    conv_tile(bg_art[i]);
    set_bkg_data(i, 1, tile_buf);
  }
  for (i = 0; i < FONT_COUNT; i++) {
    conv_glyph(font_art[i]);
    set_bkg_data((uint8_t)(T_FONT + i), 1, tile_buf);
  }
  for (i = 0; i < SPR_TILE_COUNT; i++) {
    conv_tile(spr_art[i]);
    set_sprite_data((uint8_t)(S_BASE + i), 1, tile_buf);
  }
}

/* Maps an ASCII character to its BG tile; characters outside FONT_CHARS map to T_SKY. */
uint8_t char_tile(char ch) {
  const char *p = FONT_CHARS;
  uint8_t i = 0;
  if (ch == '~') return T_FLAME;
  if (ch == '-') return T_BORDER;
  while (*p) {
    if (*p == ch) return (uint8_t)(T_FONT + i);
    p++; i++;
  }
  return T_SKY;
}
