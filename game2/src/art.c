static uint8_t tilebuf[16];

static void text_tile(const char *px) {
  uint8_t r, c, lo, hi, v;
  for (r = 0; r < 8u; r++) {
    lo = 0; hi = 0;
    for (c = 0; c < 8u; c++) {
      v = (uint8_t)(px[r * 8u + c] - '0');
      lo = (uint8_t)((lo << 1) | (v & 1u));
      hi = (uint8_t)((hi << 1) | ((v >> 1) & 1u));
    }
    tilebuf[r * 2u] = lo;
    tilebuf[r * 2u + 1u] = hi;
  }
}

void load_art(void) {
  uint8_t i, r, row;
  for (i = 0; i < BG_TILE_COUNT; i++) {
    text_tile(bg_art[i]);
    set_data((uint8_t *)(0x9000u + (uint16_t)i * 16u), tilebuf, 16u);
  }
  for (i = 0; i < SPR_TILE_COUNT; i++) {
    text_tile(spr_art[i]);
    set_data((uint8_t *)(0x8000u + (uint16_t)i * 16u), tilebuf, 16u);
  }
  for (i = 0; i < FONT_COUNT; i++) {
    for (r = 0; r < 7u; r++) {
      row = (uint8_t)(font_rows[i][r] << 2);
      tilebuf[r * 2u] = row;
      tilebuf[r * 2u + 1u] = row;
    }
    tilebuf[14] = 0; tilebuf[15] = 0;
    set_data((uint8_t *)(0x9000u + (uint16_t)(T_FONT + i) * 16u), tilebuf, 16u);
  }
}

uint8_t char_tile(char ch) {
  const char *p = FONT_CHARS;
  uint8_t i = 0;
  while (*p) {
    if (*p == ch) return (uint8_t)(T_FONT + i);
    p++; i++;
  }
  return T_VOID;
}
